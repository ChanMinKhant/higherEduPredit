    sex: { type: Number, required: true },
    age: { type: Number, required: true },
    famsize: { type: Number, required: true },
    Pstatus: { type: Number, required: true },
    Medu: { type: Number, required: true },
    Fedu: { type: Number, required: true },
    traveltime: { type: Number, required: true },
