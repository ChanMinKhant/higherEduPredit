        higher_education: { type: String, required: true },
        higher_education_no: { type: Number, required: true },
        higher_education_yes: { type: Number, required: true },
        pass_fail: { type: String, required: true },
        predicted_grade: { type: Number, required: true },
        probability_fail: { type: Number, required: true },
        probability_pass: { type: Number, required: true }
